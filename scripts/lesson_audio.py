#!/usr/bin/env python3
"""Background music and sound effects for a lesson video (needs ffmpeg).

  python scripts/lesson_audio.py make                       # makes assets/audio/{bgm,sfx}/*.wav (once)
  python scripts/lesson_audio.py mix lesson.mp4 -o out.mp4 [--markers lesson.markers.json] [--bgm FILE]

A music file dropped into assets/audio/bgm/ (mp3, m4a, ogg) is used in place of the generated pad,
looped to the video's length; its licence is yours to check (it is git-ignored, so it never leaves your machine).

`make` synthesises everything with ffmpeg's own generators: a soft looping chord pad
and two short sounds (chapter chime, scene whoosh). Nothing is downloaded or sampled,
so there is no licence to carry: the files are CC0 (public domain) by the author of
this repository. See assets/audio/CREDITS.md. To use a recorded track instead,
pass `--bgm FILE` (check its licence, and add it to CREDITS.md).

`mix` lays the music under the voice and ducks it while someone speaks
(sidechain compression), adds the chime at each chapter marker, then normalises
the result to -16 LUFS. The picture is copied, not re-encoded.
"""
from __future__ import annotations

import os
import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ASSETS = REPO / "assets" / "audio"
BGM = ASSETS / "bgm" / "soft-pad.wav"
CHIME = ASSETS / "sfx" / "chime.wav"
WHOOSH = ASSETS / "sfx" / "whoosh.wav"
LUFS = -16.0
# The music chain, shared with scripts/measure_ducking.py: every track lands at the same level, then the voice
# (the key) pulls it down while someone speaks.
MUSIC_FILTER = "loudnorm=I=-30:TP=-3:LRA=7,volume={music_db}dB"
DUCK_FILTER = "sidechaincompress=threshold=0.015:ratio=20:attack=20:release=600:makeup=1"


class AudioError(RuntimeError):
    pass


def ffmpeg() -> str:
    path = os.environ.get("OPENCUT_FFMPEG") or shutil.which("ffmpeg")
    if not path:
        raise AudioError("ffmpeg not found on PATH")
    return path


def run(cmd: list[str]) -> subprocess.CompletedProcess:
    done = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if done.returncode != 0:
        raise AudioError(f"{Path(cmd[0]).name} failed:\n{done.stderr.strip()[-800:]}")
    return done


def make() -> list[Path]:
    """Chord pad (C - Am - F - G, 8 s each, 32 s loop), chime and whoosh."""
    exe = ffmpeg()
    for d in (BGM.parent, CHIME.parent):
        d.mkdir(parents=True, exist_ok=True)
    chords = [(261.63, 329.63, 392.00), (220.00, 261.63, 329.63), (174.61, 220.00, 261.63), (196.00, 246.94, 293.66)]
    inputs: list[str] = []
    filters: list[str] = []
    for i, chord in enumerate(chords):
        for j, f in enumerate(chord):
            inputs += ["-f", "lavfi", "-t", "8.5", "-i", f"sine=frequency={f}:sample_rate=44100"]
        n = len(chord)
        base = i * n
        filters.append(
            "".join(f"[{base + k}:a]" for k in range(n))
            + f"amix=inputs={n}:normalize=0,afade=t=in:d=1.5,afade=t=out:st=7:d=1.5,volume=0.5[c{i}]"
        )
    filters.append("".join(f"[c{i}]" for i in range(len(chords))) + f"concat=n={len(chords)}:v=0:a=1,"
                   "lowpass=f=1800,tremolo=f=0.25:d=0.3,aecho=0.8:0.6:420:0.3,volume=5.2,alimiter=limit=0.8[out]")
    run([exe, "-y", "-loglevel", "error", *inputs, "-filter_complex", ";".join(filters), "-map", "[out]", "-ar", "44100", "-ac", "2", str(BGM)])
    # Chime: two soft bells (C6, E6) with a quick decay.
    run([exe, "-y", "-loglevel", "error", "-f", "lavfi", "-i", "sine=frequency=1046.5:sample_rate=44100:duration=0.9",
         "-f", "lavfi", "-i", "sine=frequency=1318.5:sample_rate=44100:duration=0.9",
         "-filter_complex", "[0:a][1:a]amix=inputs=2:normalize=0,afade=t=in:d=0.01,afade=t=out:st=0.05:d=0.85,volume=0.5[o]",
         "-map", "[o]", "-ac", "2", str(CHIME)])
    # Whoosh: a short burst of noise swept upward.
    run([exe, "-y", "-loglevel", "error", "-f", "lavfi", "-i", "anoisesrc=d=0.6:c=pink:r=44100:a=0.5",
         "-af", "highpass=f=400,lowpass=f=5000,afade=t=in:d=0.25,afade=t=out:st=0.25:d=0.35,volume=0.4", "-ac", "2", str(WHOOSH)])
    credits = ASSETS / "CREDITS.md"
    credits.write_text(
        "# Audio credits\n\n"
        "Generated by `scripts/lesson_audio.py make` with ffmpeg's built-in generators (sine, noise);\n"
        "no recording or third-party sample is used. Released as **CC0 1.0** (public domain).\n\n"
        "- `bgm/soft-pad.wav`: chord pad loop, 34 s.\n- `sfx/chime.wav`: chapter chime.\n- `sfx/whoosh.wav`: scene whoosh.\n\n"
        "A recorded track passed with `--bgm` is not covered by this: add its source and licence below.\n",
        encoding="utf-8",
    )
    return [BGM, CHIME, WHOOSH]


def chapter_times(markers: Path | None) -> list[float]:
    if not markers or not markers.exists():
        return []
    data = json.loads(markers.read_text(encoding="utf-8"))
    items = data.get("markers", data) if isinstance(data, dict) else data
    return sorted(float(m.get("time", m.get("at", 0))) for m in items if m.get("kind") == "chapter")


def user_music() -> Path | None:
    """The first mp3/m4a/ogg dropped into assets/audio/bgm/ (it wins over the generated pad)."""
    found = sorted(p for ext in ("mp3", "m4a", "ogg") for p in BGM.parent.glob(f"*.{ext}"))
    return found[0] if found else None


def mix(video: Path, out: Path, bgm: Path | None, markers: Path | None, music_db: float = 0.0) -> Path:
    exe = ffmpeg()
    bgm = bgm or user_music() or BGM
    if bgm == BGM and not bgm.exists():
        make()
    times = [t for t in chapter_times(markers) if t > 0.5]
    cmd = [exe, "-y", "-loglevel", "error", "-i", str(video), "-stream_loop", "-1", "-i", str(bgm)]
    parts = [
        # voice twice: one copy goes to the mix, one steers the compressor
        "[0:a]asplit=2[voice][key]",
        f"[1:a]{MUSIC_FILTER.format(music_db=music_db)}[music]",
        f"[music][key]{DUCK_FILTER}[ducked]",
    ]
    layers = ["[voice]", "[ducked]"]
    if times:
        cmd += ["-i", str(CHIME if CHIME.exists() else make()[1])]
        n = len(times)
        parts.append(f"[2:a]volume=-12dB,asplit={n}" + "".join(f"[s{i}]" for i in range(n)))
        for i, t in enumerate(times):
            parts.append(f"[s{i}]adelay={int(t * 1000)}|{int(t * 1000)}[d{i}]")
            layers.append(f"[d{i}]")
    parts.append("".join(layers) + f"amix=inputs={len(layers)}:duration=first:normalize=0,"
                 f"loudnorm=I={LUFS}:TP=-1.0:LRA=11[a]")
    cmd += ["-filter_complex", ";".join(parts), "-map", "0:v", "-map", "[a]", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-shortest", str(out)]
    run(cmd)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("make", help="Synthesise the music and sound effects (once)")
    m = sub.add_parser("mix", help="Music under the voice (ducked), chapter chimes, -16 LUFS")
    m.add_argument("video")
    m.add_argument("-o", "--out", required=True)
    m.add_argument("--markers", help="<name>.markers.json: a chime at each chapter")
    m.add_argument("--bgm", help="A music file to use instead of the generated pad")
    m.add_argument("--music-db", type=float, default=0.0, help="Music level before ducking, relative to -30 LUFS (default 0)")
    args = parser.parse_args(argv)
    try:
        if args.command == "make":
            for p in make():
                print(p)
        else:
            print(mix(Path(args.video), Path(args.out), Path(args.bgm) if args.bgm else None,
                      Path(args.markers) if args.markers else None, args.music_db))
        return 0
    except AudioError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
